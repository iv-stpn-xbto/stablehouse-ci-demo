import { randomBytes } from "node:crypto";
import { createInterface } from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import { writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { requiredPackagesForPaths } from "./check-changeset-scope.mjs";

const RELEASE_TYPES = new Set(["patch", "minor", "major"]);
const APPS = new Set(["web", "backoffice"]);

export function parseAddArgs(argv) {
  const [bump, ...rest] = argv;
  if (!RELEASE_TYPES.has(bump)) {
    throw new TypeError("Usage: add-changeset.mjs <patch|minor|major> [app...] [-m summary]");
  }

  const apps = [];
  let summary;
  for (let index = 0; index < rest.length; index += 1) {
    const token = rest[index];
    if (token === "-m" || token === "--message") {
      summary = rest[index + 1];
      if (!summary) throw new TypeError("Missing summary after -m");
      index += 1;
      continue;
    }
    if (token.startsWith("-")) {
      throw new TypeError(`Unknown flag: ${token}`);
    }
    if (!APPS.has(token)) {
      throw new TypeError(`Unknown package ${token}; expected web or backoffice`);
    }
    apps.push(token);
  }

  return { bump, apps: [...new Set(apps)], summary };
}

export function appsFromChangedPaths(paths) {
  const required = requiredPackagesForPaths(paths);
  const appOnly = [...required].filter((name) => APPS.has(name));
  const touchesCommon = paths.some((path) => path.startsWith("packages/common/"));
  const touchesApp = paths.some(
    (path) => path.startsWith("apps/web/") || path.startsWith("apps/backoffice/"),
  );
  return { apps: appOnly, touchesCommon, touchesApp };
}

export function changesetMarkdown(app, bump, summary) {
  const text = String(summary)
    .replace(/[\u0000-\u001f\u007f]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!text) throw new TypeError("Changeset summary must contain visible text");
  return `---
"${app}": ${bump}
---

${text}
`;
}

function gitPaths(args) {
  const result = spawnSync("git", args, { encoding: "utf8" });
  if (result.status !== 0) return [];
  return result.stdout.split("\n").filter(Boolean);
}

function changedPaths() {
  return [
    ...new Set([
      ...gitPaths(["diff", "--name-only", "develop...HEAD"]),
      ...gitPaths(["diff", "--name-only", "develop"]),
      ...gitPaths(["diff", "--name-only", "--cached"]),
      ...gitPaths(["diff", "--name-only"]),
    ]),
  ];
}

async function resolveSummary(provided) {
  if (provided) return provided;
  if (!input.isTTY) {
    throw new TypeError("Pass -m \"summary\" when stdin is not a terminal");
  }
  const rl = createInterface({ input, output });
  try {
    const answer = await rl.question("Summary: ");
    return answer;
  } finally {
    rl.close();
  }
}

async function main() {
  const parsed = parseAddArgs(process.argv.slice(2));
  const paths = changedPaths();
  const inferred = appsFromChangedPaths(paths);

  if (inferred.touchesCommon && !inferred.touchesApp && parsed.apps.length === 0) {
    throw new Error(
      "common changesets are generated by CI. Do not run yarn changeset for packages/common.",
    );
  }

  const apps = parsed.apps.length > 0 ? parsed.apps : inferred.apps.filter((app) => {
    if (app === "web") return paths.some((path) => path.startsWith("apps/web/"));
    if (app === "backoffice") return paths.some((path) => path.startsWith("apps/backoffice/"));
    return false;
  });

  if (apps.length === 0) {
    throw new Error(
      "No app package inferred. Pass web and/or backoffice, e.g. yarn changeset web",
    );
  }

  const summary = await resolveSummary(parsed.summary);
  const written = [];
  for (const app of apps) {
    const name = `${parsed.bump}-${app}-${randomBytes(4).toString("hex")}.md`;
    const path = `.changeset/${name}`;
    await writeFile(path, changesetMarkdown(app, parsed.bump, summary), "utf8");
    written.push(path);
  }
  console.log(`Wrote ${parsed.bump} changeset(s):\n${written.map((path) => `- ${path}`).join("\n")}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
